package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
)

// emit writes dpt/masterdata_gen.go.
func emit(lk lock, md *masterData) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by gendpt from the KNX master data. DO NOT EDIT.\n\n")
	b.WriteString("// SPDX-License-Identifier: MIT\n\n")
	b.WriteString("package dpt\n\n")
	b.WriteString("// The KNX master data this file was generated from (dpt/masterdata.lock).\n")
	b.WriteString("const (\n")
	fmt.Fprintf(&b, "masterDataURL = %q\n", lk.URL)
	fmt.Fprintf(&b, "masterDataSchema = %d\n", md.Schema)
	fmt.Fprintf(&b, "masterDataVersion = %d\n", md.Version)
	fmt.Fprintf(&b, "masterDataSHA256 = %q\n", lk.SHA256)
	b.WriteString(")\n\n")
	b.WriteString("// masterSubtypes are the datapoint subtypes of the master data, by identifier.\n")
	b.WriteString("var masterSubtypes = []mdSubtype{\n")
	for _, s := range md.Subtypes {
		fmt.Fprintf(&b, "{ID: ID{%d, %d}, Name: %q, Text: %q, Bits: %d", s.Main, s.Sub, s.Name, s.Text, s.Bits)
		if len(s.Fields) > 0 {
			b.WriteString(", Fields: []mdField{\n")
			for _, f := range s.Fields {
				writeField(&b, f)
			}
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func writeField(b *bytes.Buffer, f field) {
	fmt.Fprintf(b, "{Kind: %s, Width: %d", f.Kind, f.Width)
	str := func(name, v string) {
		if v != "" {
			fmt.Fprintf(b, ", %s: %q", name, v)
		}
	}
	str("Name", f.Name)
	str("Unit", f.Unit)
	str("Cleared", f.Cleared)
	str("Set", f.Set)
	if f.HasRange {
		fmt.Fprintf(b, ", Min: %s, Max: %s, HasRange: true", num(f.Min), num(f.Max))
	}
	if f.Coefficient != 0 {
		fmt.Fprintf(b, ", Coefficient: %s", num(f.Coefficient))
	}
	str("Encoding", f.Encoding)
	if len(f.Enum) > 0 {
		b.WriteString(", Enum: []mdEnumValue{")
		for i, v := range f.Enum {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(b, "{%d, %q}", v.Value, v.Text)
		}
		b.WriteString("}")
	}
	b.WriteString("},\n")
}

// num writes a float64 as the shortest Go literal that reads back to it.
func num(v float64) string {
	return strconv.FormatFloat(v, 'g', -1, 64)
}
